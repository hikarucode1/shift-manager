/**
 * 固定シフト登録の画面に出す注意書き (#319)。教室のレギュラーエクセルの文言を
 * もとにしている。教室長が編集する画面は作っていないので、変えるときはここを直す。
 *
 * エクセルとの違い:
 * - 「前期分という事で7月末まで」は期によって変わるので、受付中の期の終了日を出す
 * - 講習月はエクセルの「3・4月、7・8月、12・1・2月」に 9 月を足した
 *   (2026-11-12 本人の説明: レギュラーで組むのは 5・6 月と 10・11 月だけで、
 *   それ以外は前月に日にちごとに聞く)
 * - 「いつまで？」はアプリでは「適用終了日」
 */
export function regularSubmissionNotes(periodEndDate: string | null): string[] {
  const until = periodEndDate
    ? `この期の終わり（${formatMonthDay(periodEndDate)}）まで`
    : "その期の終わりまで";
  return [
    "必ずしも希望通りになるとは限りません。",
    "講習月（3・4月、7〜9月、12〜2月）は、従来どおり月ごとのシフトです。",
    "通常月は、成績アップの観点から担当制を敷いています。相性、授業可能科目、曜日・時間が固定の生徒などを総合的に見て決めます。",
    `原則、${until}を想定しています。クォーター制など履修が変わる場合は「適用終了日」に記入してください。`,
    "提出したからといって、すぐにスケジュールが変わるわけではありません。",
  ];
}

/** "2027-07-31" → "7月31日" */
function formatMonthDay(iso: string): string {
  const [, m, d] = iso.split("-").map(Number);
  return `${m}月${d}日`;
}
