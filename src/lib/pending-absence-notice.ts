/**
 * 「未対応」タブの欠勤カードに出す、担当が変わったことの知らせ (#289)。
 *
 * 代講の取り消し・CSV の取り込みなどで担当が変わると (#259 の 5 経路)、元の
 * 担当者の欠勤申請が「未対応」に残る。教室長には、それに気づく手がかりが
 * 無かった。
 *
 * ⚠️ **承認は塞がない** (PR #290 のレビューで方針を変えた)。教室長が A の休みを
 * 知って CSV で A のコマを B に差し替えると、A の欠勤は「担当ではない」になるが、
 * 実際に休んだ記録として**承認するのが正しい**。塞ぐと却下しか選べず、A に
 * 「却下されました」(=出勤しろ) が届き、記録も「却下」で残る。承認しても、
 * 担当でないコマには週次表の欠勤マークが出ない (講師・日付・コマの組で付く)
 * ので害は無い。事情を伝えて、教室長に選んでもらう
 */
export const ABSENCE_UNASSIGNED_NOTICE =
  "このコマは今は担当ではありません（担当が変わりました）。実際に休んだ記録として残すなら承認、不要なら却下してください。";

/** 担当でなくなっていれば知らせの一文、今も担当なら null */
export function pendingAbsenceNotice(s: {
  tutorAssigned: boolean;
}): string | null {
  return s.tutorAssigned ? null : ABSENCE_UNASSIGNED_NOTICE;
}
